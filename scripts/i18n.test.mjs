// Tests of the spreadsheet import (scripts/i18n/messages.mjs apply). Rows are JSON, as import_text.py
// writes them from the workbook, so these tests need no Python.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, beforeEach, test } from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCRIPT = path.join(ROOT, "scripts/i18n/messages.mjs");

let dir;
let files;

beforeEach(() => {
  dir = mkdtempSync(path.join(tmpdir(), "i18n-test-"));
  files = {
    en: path.join(dir, "en.ts"),
    glossary: path.join(dir, "glossary.ts"),
    vi: path.join(dir, "vi.ts"),
    serverText: path.join(dir, "server-text.ts"),
  };
  copyFileSync(path.join(ROOT, "apps/web/src/messages/en.ts"), files.en);
  copyFileSync(path.join(ROOT, "packages/shared/src/glossary.ts"), files.glossary);
});

afterEach(() => rmSync(dir, { recursive: true, force: true }));

const paths = () => [
  "--en",
  files.en,
  "--glossary",
  files.glossary,
  "--vi",
  files.vi,
  "--server-text",
  files.serverText,
];

function run(...args) {
  return spawnSync(process.execPath, [SCRIPT, ...args, ...paths()], { encoding: "utf8" });
}

function dump() {
  const r = run("dump");
  assert.equal(r.status, 0, r.stderr);
  return JSON.parse(r.stdout);
}

const PREFIXES = [
  ["server.096", "Question {i + 1}: ", "Câu hỏi {i + 1}:"],
  ["server.113", "Your work was scored: ", "Bài của bạn đã được chấm điểm:"],
  ["server.114", "Please change your work: ", "Vui lòng chỉnh sửa bài:"],
  ["server.120", "New homework: ", "Bài tập mới:"],
  ["server.121", "Due soon: ", "Sắp đến hạn nộp:"],
];

/** A full set of rows: every web key with a made-up Vietnamese text, and a few real server texts. */
function rows() {
  const web = dump().map(({ key, text }) => ({ key, source: text, en: text, vi: `VI ${text}` }));
  const server = [
    {
      key: "server.002",
      source: "Please sign in to continue.",
      en: "Please sign in to continue.",
      vi: "Vui lòng đăng nhập.",
    },
    {
      key: "server.175",
      source: "{s.name} handed in work",
      en: "{s.name} handed in work",
      vi: "{s.name} đã nộp bài",
    },
    ...PREFIXES.map(([key, id, vi]) => ({ key, source: id, en: id.trimEnd(), vi })),
  ];
  return [...web, ...server];
}

function apply(list) {
  const json = path.join(dir, "rows.json");
  writeFileSync(json, JSON.stringify(list));
  return run("apply", json);
}

const snapshot = () =>
  Object.fromEntries(
    Object.entries(files).map(([k, f]) => [k, existsSync(f) ? readFileSync(f, "utf8") : null]),
  );

const set = (list, key, change) => list.map((r) => (r.key === key ? { ...r, ...change } : r));

function assertRefused(result, before, ...words) {
  assert.notEqual(result.status, 0, "the import must fail");
  for (const w of words) assert.match(result.stderr, new RegExp(w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
  assert.deepEqual(snapshot(), before, "no file may change");
}

test("dump lists every web text, the glossary included", () => {
  const list = dump();
  const keys = list.map((r) => r.key);
  assert.ok(list.length > 900);
  assert.equal(new Set(keys).size, keys.length);
  assert.deepEqual(
    list.find((r) => r.key === "glossary.course"),
    { key: "glossary.course", text: "Course" },
  );
  assert.deepEqual(
    list.find((r) => r.key === "common.back"),
    { key: "common.back", text: "Back" },
  );
});

test("code-like text in a cell ends up as that exact string, and the files import cleanly", async () => {
  const hostile = '`"; process.exit()//${name}';
  // No closing brace, so it has no placeholder.
  const plain = "a `tick` ${process.exit()\"quote\" 'single' */ /* \\ end\nnew line   </script>";
  let list = set(rows(), "roster.removeText", { vi: hostile });
  list = set(list, "common.back", { vi: plain });
  list = set(list, "server.002", { vi: plain });
  const r = apply(list);
  assert.equal(r.status, 0, r.stderr);

  const viText = readFileSync(files.vi, "utf8");
  assert.ok(viText.startsWith("// Generated by scripts/i18n/import_text.py from the text spreadsheet."));
  assert.ok(viText.includes(JSON.stringify(hostile)) || viText.includes(`'${hostile.replace(/'/g, "\\'")}'`));

  const { vi } = await import(pathToFileURL(files.vi).href);
  assert.equal(vi.roster.removeText, hostile);
  assert.equal(vi.common.back, plain);
  assert.equal(vi.common.cancel, "VI Cancel");
  assert.equal(vi.glossary.course, "VI Course");

  const { SERVER_TEXT } = await import(pathToFileURL(files.serverText).href);
  assert.ok(readFileSync(files.serverText, "utf8").startsWith("// Generated by scripts/i18n/import_text.py"));
  assert.deepEqual(
    SERVER_TEXT.find((e) => e.id === "Please sign in to continue."),
    {
      id: "Please sign in to continue.",
      en: "Please sign in to continue.",
      vi: plain,
    },
  );
  assert.deepEqual(
    SERVER_TEXT.find((e) => e.id === "{s.name} handed in work"),
    {
      id: "{s.name} handed in work",
      en: "{s.name} handed in work",
      vi: "{s.name} đã nộp bài",
    },
  );
});

test("the leading and trailing spaces of the English id are kept on every language", async () => {
  const r = apply(rows());
  assert.equal(r.status, 0, r.stderr);
  const { SERVER_TEXT } = await import(pathToFileURL(files.serverText).href);
  for (const [, id, vi] of PREFIXES) {
    assert.deepEqual(
      SERVER_TEXT.find((e) => e.id === id),
      { id, en: id, vi: `${vi} ` },
    );
  }
});

test("a cell left empty uses the English text", async () => {
  const r = apply(set(rows(), "common.back", { vi: null }));
  assert.equal(r.status, 0, r.stderr);
  const { vi } = await import(pathToFileURL(files.vi).href);
  assert.equal(vi.common.back, "Back");
});

test("a Vietnamese text without a placeholder of the English is refused, naming the key", () => {
  const before = snapshot();
  const r = apply(set(rows(), "roster.removeText", { vi: "Học sinh sẽ không thấy khóa học này nữa." }));
  assertRefused(r, before, "roster.removeText", "{name}");
});

test("an English text with a different placeholder is refused", () => {
  const before = snapshot();
  const r = apply(set(rows(), "server.175", { en: "{name} handed in work" }));
  assertRefused(r, before, "server.175");
});

test("an unknown key is refused", () => {
  const before = snapshot();
  const r = apply([...rows(), { key: "landing.nope", source: "x", en: "x", vi: "x" }]);
  assertRefused(r, before, "landing.nope");
});

test("a server text that is not in the code is refused", () => {
  const before = snapshot();
  const r = apply([...rows(), { key: "server.200", source: "Made up text.", en: "Made up text.", vi: "x" }]);
  assertRefused(r, before, "server.200");
});

test("a missing key is refused", () => {
  const before = snapshot();
  const r = apply(rows().filter((row) => row.key !== "common.back"));
  assertRefused(r, before, "common.back");
});

test("a duplicate key is refused", () => {
  const before = snapshot();
  const list = rows();
  const r = apply([...list, list.find((row) => row.key === "common.cancel")]);
  assertRefused(r, before, "common.cancel");
});

test("a missing server text that is in the current table is refused", () => {
  assert.equal(apply(rows()).status, 0);
  const before = snapshot();
  const r = apply(rows().filter((row) => row.key !== "server.002"));
  assertRefused(r, before, "Please sign in to continue.");
});

test("rows that are not a list of rows are refused", () => {
  const before = snapshot();
  assertRefused(apply({ rows: [] }), before);
  assertRefused(apply([...rows(), { key: "common.back2", en: 5 }]), before);
  assertRefused(apply(set(rows(), "common.back", { vi: 7 })), before, "common.back");
});

test("an edited English text changes only that text in en.ts; comments and other lines stay", () => {
  const before = readFileSync(files.en, "utf8");
  const r = apply(set(rows(), "common.back", { en: "Go back" }));
  assert.equal(r.status, 0, r.stderr);
  const after = readFileSync(files.en, "utf8");
  const a = before.split("\n");
  const b = after.split("\n");
  assert.equal(b.length, a.length);
  const changed = a.map((line, i) => (line === b[i] ? null : [line, b[i]])).filter(Boolean);
  assert.deepEqual(changed, [['    back: "Back",', '    back: "Go back",']]);
  assert.equal(
    readFileSync(files.glossary, "utf8"),
    readFileSync(path.join(ROOT, "packages/shared/src/glossary.ts"), "utf8"),
  );
  assert.deepEqual(
    dump().find((x) => x.key === "common.back"),
    { key: "common.back", text: "Go back" },
  );
});

test("an edited glossary text changes the glossary file", () => {
  const r = apply(set(rows(), "glossary.course", { en: "Class" }));
  assert.equal(r.status, 0, r.stderr);
  assert.match(readFileSync(files.glossary, "utf8"), /\n {2}course: "Class",\n/);
});

test("an English text changed both in the code and in the file is refused", () => {
  const before = snapshot();
  const r = apply(set(rows(), "common.back", { source: "Back please", en: "Go back" }));
  assertRefused(r, before, "common.back");
});

test("an English text changed in the code since the export, but not in the file, keeps the code's text", () => {
  const before = readFileSync(files.en, "utf8");
  const r = apply(set(rows(), "common.back", { source: "Back please", en: "Back please" }));
  assert.equal(r.status, 0, r.stderr);
  assert.equal(readFileSync(files.en, "utf8"), before);
});

test("a made-up pattern id is refused even if its fixed parts are somewhere in the code", () => {
  const before = snapshot();
  for (const id of ["{a} {b}", "{a}e{b}e{c}e{d}e{e}!"]) {
    const r = apply([...rows(), { key: "server.300", source: id, en: id, vi: "HIJACK" + id }]);
    assertRefused(r, before, "server.300", id);
  }
});

test("a server id already in the table is accepted even if the scan does not find it", () => {
  const id = "Kept from an earlier table.";
  writeFileSync(
    files.serverText,
    `export const SERVER_TEXT = [{ id: ${JSON.stringify(id)}, en: ${JSON.stringify(id)}, vi: "Giữ lại." }];\n`,
  );
  const r = apply([...rows(), { key: "server.300", source: id, en: id, vi: "Giữ lại." }]);
  assert.equal(r.status, 0, r.stderr);
});

// The notification titles are stored as one of these prefixes and the homework title (SQL `||`), so the table
// also gets a pattern "<prefix>{title}" for each of them. These entries are made by the import, not read from it.
const NOTICE_PREFIXES = PREFIXES.filter(([, id]) => !id.startsWith("Question"));

test("each notification prefix also gets a pattern for the title after it", async () => {
  const r = apply(rows());
  assert.equal(r.status, 0, r.stderr);
  const { SERVER_TEXT } = await import(pathToFileURL(files.serverText).href);
  assert.equal(NOTICE_PREFIXES.length, 4);
  for (const [, id, vi] of NOTICE_PREFIXES) {
    assert.deepEqual(
      SERVER_TEXT.find((e) => e.id === `${id}{title}`),
      { id: `${id}{title}`, en: `${id}{title}`, vi: `${vi} {title}` },
    );
  }
  // Only those four: other texts ending in a space get no pattern.
  assert.equal(SERVER_TEXT.filter((e) => e.id.endsWith("{title}")).length, 4);
});

test("importing again does not ask for the made patterns, and a row cannot set one", async () => {
  assert.equal(apply(rows()).status, 0);
  const again = apply(rows());
  assert.equal(again.status, 0, again.stderr);
  const { SERVER_TEXT } = await import(`${pathToFileURL(files.serverText).href}?again`);
  assert.equal(SERVER_TEXT.filter((e) => e.id === "New homework: {title}").length, 1);

  const before = snapshot();
  const id = "New homework: {title}";
  const r = apply([...rows(), { key: "server.300", source: id, en: id, vi: "HIJACK {title}" }]);
  assertRefused(r, before, "server.300", id);
});

test("the export does not list the made patterns as rows", () => {
  assert.equal(apply(rows()).status, 0);
  const r = run("rows");
  assert.equal(r.status, 0, r.stderr);
  const ids = JSON.parse(r.stdout).server.map((s) => s.id);
  assert.ok(ids.includes("New homework: "));
  assert.ok(!ids.some((id) => id.endsWith("{title}")));
});
