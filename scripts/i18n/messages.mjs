// Reads and writes the text catalogs for the text spreadsheet. Python (export_text.py, import_text.py) only turns
// the workbook into JSON and back; every check of the owner's file happens here.
//
//   node scripts/i18n/messages.mjs dump               web texts of en.ts as [{ key, text }]
//   node scripts/i18n/messages.mjs rows               every row for the export (web, then server texts)
//   node scripts/i18n/messages.mjs apply <rows.json>  check the rows, then write en.ts, vi.ts and server-text.ts
//
// Options (for tests): --en, --glossary, --vi, --server-text <path>.
//
// Safety: keys come only from en.ts and the current table; the file only gives text. Every text is written
// into code with JSON.stringify. Nothing is written unless every row is valid, and the generated files are
// parsed back and compared with the intended text before they are written.
import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, literalParts, scanServer, sourceFiles } from "./scan-server.mjs";

const ts = createRequire(path.join(ROOT, "apps/web/package.json"))("typescript");

export const HEADER =
  "// Generated by scripts/i18n/import_text.py from the text spreadsheet. Do not edit by hand.";
const SERVER_KEY = /^server\.\d{1,4}$/;
const SAFE_SEGMENT = /^[A-Za-z_$][\w$]*$/;
const PLACEHOLDER = /\{[^{}]*\}/g;

class Refused extends Error {}

// ------------------------------------------------------------------ reading catalogs

const parse = (file, text) => ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);

function unwrap(node) {
  while (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node)) {
    node = node.expression;
  }
  return node;
}

function exportedConst(source, name) {
  for (const st of source.statements) {
    if (!ts.isVariableStatement(st)) continue;
    for (const d of st.declarationList.declarations) {
      if (ts.isIdentifier(d.name) && d.name.text === name && d.initializer) return unwrap(d.initializer);
    }
  }
  throw new Error(`${source.fileName}: no "${name}" object`);
}

const propertyName = (p, file) => {
  if (ts.isIdentifier(p.name) || ts.isStringLiteral(p.name)) return p.name.text;
  throw new Error(`${file}: unsupported property name ${p.name.getText()}`);
};

/**
 * Walks an object literal of texts. Returns the texts in order ({ key, text, file, start, end }) and the shape
 * (a tree of { name, children } | { name, key }) used to write another language with the same structure.
 */
function walk(node, prefix, file, resolve, out) {
  node = unwrap(node);
  if (!ts.isObjectLiteralExpression(node)) throw new Error(`${file}: "${prefix}" is not an object`);
  const children = [];
  for (const p of node.properties) {
    if (!ts.isPropertyAssignment(p)) throw new Error(`${file}: unsupported entry ${p.getText()}`);
    const name = propertyName(p, file);
    if (!SAFE_SEGMENT.test(name) || name === "__proto__") throw new Error(`${file}: unsafe key "${name}"`);
    const key = prefix ? `${prefix}.${name}` : name;
    let value = unwrap(p.initializer);
    let valueFile = file;
    if (ts.isIdentifier(value)) {
      const target = resolve(value.text);
      if (!target) throw new Error(`${file}: cannot resolve ${value.text}`);
      value = target.node;
      valueFile = target.file;
    }
    if (ts.isStringLiteral(value) || ts.isNoSubstitutionTemplateLiteral(value)) {
      out.push({ key, text: value.text, file: valueFile, start: value.getStart(), end: value.getEnd() });
      children.push({ name, key });
    } else {
      children.push({ name, children: walk(value, key, valueFile, resolve, out).children });
    }
  }
  return { children, texts: out };
}

/** The web catalog: en.ts with GLOSSARY taken from the glossary file. */
function readWeb(opts, sources = {}) {
  const enText = sources.en ?? readFileSync(opts.en, "utf8");
  const glText = sources.glossary ?? readFileSync(opts.glossary, "utf8");
  const enSrc = parse(opts.en, enText);
  const glSrc = parse(opts.glossary, glText);
  const resolve = (name) =>
    name === "GLOSSARY" ? { node: exportedConst(glSrc, "GLOSSARY"), file: opts.glossary } : null;
  const { children, texts } = walk(exportedConst(enSrc, "en"), "", opts.en, resolve, []);
  return { tree: children, texts, files: { [opts.en]: enText, [opts.glossary]: glText } };
}

/** The texts of a generated vi.ts (no identifiers allowed). */
function readVi(file, text) {
  const { texts } = walk(exportedConst(parse(file, text), "vi"), "", file, () => null, []);
  return texts;
}

/** The entries of a server-text.ts; an empty list when the file does not exist yet. */
function readServerText(file, text = existsSync(file) ? readFileSync(file, "utf8") : null) {
  if (text === null) return [];
  const list = exportedConst(parse(file, text), "SERVER_TEXT");
  if (!ts.isArrayLiteralExpression(list)) throw new Error(`${file}: SERVER_TEXT is not a list`);
  return list.elements.map((el) => {
    el = unwrap(el);
    if (!ts.isObjectLiteralExpression(el)) throw new Error(`${file}: unsupported entry ${el.getText()}`);
    const entry = {};
    for (const p of el.properties) {
      const name = ts.isPropertyAssignment(p) ? propertyName(p, file) : "";
      const v = ts.isPropertyAssignment(p) ? unwrap(p.initializer) : null;
      if (
        !["id", "en", "vi"].includes(name) ||
        !(ts.isStringLiteral(v) || ts.isNoSubstitutionTemplateLiteral(v))
      ) {
        throw new Error(`${file}: unsupported entry ${el.getText()}`);
      }
      entry[name] = v.text;
    }
    if (typeof entry.id !== "string" || typeof entry.en !== "string" || typeof entry.vi !== "string") {
      throw new Error(`${file}: incomplete entry ${el.getText()}`);
    }
    return { id: entry.id, en: entry.en, vi: entry.vi };
  });
}

// ------------------------------------------------------------------ checks

const holders = (s) => JSON.stringify((s.match(PLACEHOLDER) ?? []).sort());
const lead = (s) => /^\s*/.exec(s)[0];
const trail = (s) => /\s*$/.exec(s)[0];
/** The value with the leading and trailing spaces of `base` (the English id). */
const spaced = (value, base) => (base.trim() === "" ? base : lead(base) + value.trim() + trail(base));
const isText = (v) => typeof v === "string";
const isEmpty = (v) => v === null || v === undefined || (isText(v) && v.trim() === "");

let codeTexts = null;
/** Ruling A: every fixed part of the id is in one source file (SQL builds texts with ||). */
function inCode(id) {
  codeTexts ??= sourceFiles().map((f) => readFileSync(f, "utf8"));
  const parts = literalParts(id);
  return parts.length > 0 && codeTexts.some((text) => parts.every((p) => text.includes(p)));
}

/** Checks the rows and works out what to write. Throws Refused with every problem found. */
export function plan(rows, web, table) {
  const errors = [];
  if (!Array.isArray(rows)) throw new Refused("The rows are not a list.");
  const webByKey = new Map(web.texts.map((t) => [t.key, t]));
  const seen = new Set();
  const seenIds = new Set();
  const viByKey = new Map();
  const edits = [];
  const server = [];

  rows.forEach((row, i) => {
    const name = row && isText(row.key) ? row.key : `row ${i + 1}`;
    const bad = (msg) => errors.push(`${name}: ${msg}`);
    if (!row || typeof row !== "object" || Array.isArray(row) || !isText(row.key))
      return bad("not a row with a key");
    if (seen.has(row.key)) return bad("the key is in the file more than once");
    seen.add(row.key);
    for (const f of ["source", "en", "vi"]) {
      if (!isEmpty(row[f]) && !isText(row[f])) return bad(`the ${f} cell is not text`);
    }
    if (isEmpty(row.en)) return bad("the en cell is empty");

    let base;
    if (SERVER_KEY.test(row.key)) {
      if (isEmpty(row.source)) return bad("no English id in the _map sheet");
      base = row.source;
      if (seenIds.has(base)) return bad(`the text "${base}" is in the file more than once`);
      seenIds.add(base);
      if (!inCode(base)) return bad(`the text "${base}" is not in the code`);
    } else {
      const current = webByKey.get(row.key);
      if (!current) return bad("unknown key (not in apps/web/src/messages/en.ts)");
      base = current.text;
    }

    const enCell = spaced(row.en, base);
    let en = enCell;
    if (!SERVER_KEY.test(row.key)) {
      // A web text: the English of the code wins unless the owner edited the cell (compared with the English
      // the file was exported with, kept in the _map sheet).
      const source = isEmpty(row.source) ? base : spaced(row.source, base);
      const edited = enCell !== source;
      if (edited && source !== base) {
        bad(`the English was changed both in the code ("${base}") and in the file ("${enCell}")`);
      }
      en = edited ? enCell : base;
      if (en !== base) edits.push({ ...webByKey.get(row.key), value: en });
    }
    const vi = isEmpty(row.vi) ? en : spaced(row.vi, base);
    if (holders(en) !== holders(base)) bad(`the en text must keep the placeholders of "${base}"`);
    if (holders(vi) !== holders(base)) bad(`the vi text must keep the placeholders of "${base}"`);

    if (SERVER_KEY.test(row.key)) server.push({ id: base, en, vi });
    else viByKey.set(row.key, vi);
  });

  for (const t of web.texts) if (!seen.has(t.key)) errors.push(`${t.key}: missing from the file`);
  for (const e of table) if (!seenIds.has(e.id)) errors.push(`server text "${e.id}": missing from the file`);
  if (errors.length) throw new Refused(errors.join("\n"));
  // The table keeps its order (the file's row numbers change between exports); new texts go at the end.
  const position = new Map(table.map((e, i) => [e.id, i]));
  const at = (e) => position.get(e.id) ?? table.length;
  server.sort((a, b) => at(a) - at(b));
  return { edits, viByKey, server };
}

// ------------------------------------------------------------------ writing

function viSource(tree, viByKey) {
  const obj = (children, indent) => {
    const pad = "  ".repeat(indent);
    const lines = children.map((c) =>
      "key" in c
        ? `${pad}${JSON.stringify(c.name)}: ${JSON.stringify(viByKey.get(c.key))},`
        : `${pad}${JSON.stringify(c.name)}: ${obj(c.children, indent + 1)},`,
    );
    return `{\n${lines.join("\n")}\n${"  ".repeat(indent - 1)}}`;
  };
  return `${HEADER}\nimport type { Messages } from "./en";\n\nexport const vi: Messages = ${obj(tree, 1)};\n`;
}

function serverSource(entries) {
  const lines = entries.map(
    (e) => `  { id: ${JSON.stringify(e.id)}, en: ${JSON.stringify(e.en)}, vi: ${JSON.stringify(e.vi)} },`,
  );
  return `${HEADER}\nimport type { ServerText } from "./languages";\n\nexport const SERVER_TEXT: readonly ServerText[] = [\n${lines.join("\n")}\n];\n`;
}

/** Replaces string literals by position, last first, so earlier positions stay valid. */
function editSource(text, edits) {
  let out = text;
  for (const e of [...edits].sort((a, b) => b.start - a.start)) {
    out = out.slice(0, e.start) + JSON.stringify(e.value) + out.slice(e.end);
  }
  return out;
}

async function format(text, file) {
  const prettier = await import("prettier");
  const config = JSON.parse(readFileSync(path.join(ROOT, ".prettierrc.json"), "utf8"));
  return prettier.format(text, { ...config, filepath: file.replace(/\.ts$/, "") + ".ts" });
}

function syntaxErrors(file, text) {
  return parse(file, text).parseDiagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
}

/** Builds every output file, then parses each one back and compares it with what was meant. */
async function build(opts, web, { edits, viByKey, server }) {
  const outputs = new Map();
  const byFile = new Map();
  for (const e of edits) byFile.set(e.file, [...(byFile.get(e.file) ?? []), e]);
  for (const [file, list] of byFile) outputs.set(file, await format(editSource(web.files[file], list), file));
  outputs.set(opts.vi, await format(viSource(web.tree, viByKey), opts.vi));
  outputs.set(opts.serverText, await format(serverSource(server), opts.serverText));

  for (const [file, text] of outputs) {
    const problems = syntaxErrors(file, text);
    if (problems.length) throw new Error(`${file} would not compile: ${problems.join("; ")}`);
  }
  const fresh = readWeb(opts, { en: outputs.get(opts.en), glossary: outputs.get(opts.glossary) });
  const wanted = new Map(web.texts.map((t) => [t.key, t.text]));
  for (const e of edits) wanted.set(e.key, e.value);
  const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
  if (
    !same(
      fresh.texts.map((t) => [t.key, t.text]),
      [...wanted],
    )
  )
    throw new Error("en.ts check failed");
  const viBack = readVi(opts.vi, outputs.get(opts.vi)).map((t) => [t.key, t.text]);
  if (
    !same(
      viBack,
      web.texts.map((t) => [t.key, viByKey.get(t.key)]),
    )
  )
    throw new Error("vi.ts check failed");
  if (!same(readServerText(opts.serverText, outputs.get(opts.serverText)), server)) {
    throw new Error("server-text.ts check failed");
  }
  return outputs;
}

function writeAll(outputs) {
  const temp = [...outputs].map(([file, text]) => {
    const t = `${file}.tmp-${process.pid}`;
    writeFileSync(t, text);
    return [t, file];
  });
  for (const [t, file] of temp) renameSync(t, file);
}

// ------------------------------------------------------------------ export rows

const SERVER_GROUP_DEFAULT = "34 Máy chủ - lỗi khi thao tác";

/** Rows for export_text.py: web texts with the current Vietnamese, then the server texts and new code texts. */
function exportRows(opts) {
  const web = readWeb(opts);
  const viText = existsSync(opts.vi) ? readFileSync(opts.vi, "utf8") : null;
  const vi = new Map(viText ? readVi(opts.vi, viText).map((t) => [t.key, t.text]) : []);
  const table = readServerText(opts.serverText);
  const scan = new Map(scanServer().map((s) => [s.id, s]));
  const server = table.map((e) => ({
    id: e.id,
    en: e.en,
    vi: e.vi,
    where: scan.get(e.id)?.where ?? [],
    group: scan.get(e.id)?.group ?? SERVER_GROUP_DEFAULT,
    new: false,
  }));
  const known = new Set(table.map((e) => e.id));
  for (const s of scan.values()) {
    if (!known.has(s.id))
      server.push({ id: s.id, en: s.id, vi: null, where: s.where, group: s.group, new: true });
  }
  server.sort((a, b) => a.group.localeCompare(b.group));
  server.forEach((s, i) => (s.key = `server.${String(i + 1).padStart(3, "0")}`));
  return {
    web: web.texts.map((t) => ({ key: t.key, en: t.text, vi: vi.get(t.key) ?? null })),
    server,
  };
}

// ------------------------------------------------------------------ command line

function options(argv) {
  const opts = {
    en: path.join(ROOT, "apps/web/src/messages/en.ts"),
    glossary: path.join(ROOT, "packages/shared/src/glossary.ts"),
    vi: path.join(ROOT, "apps/web/src/messages/vi.ts"),
    serverText: path.join(ROOT, "packages/shared/src/i18n/server-text.ts"),
  };
  const flags = { "--en": "en", "--glossary": "glossary", "--vi": "vi", "--server-text": "serverText" };
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    if (flags[argv[i]]) {
      if (!argv[i + 1]) throw new Refused(`${argv[i]} needs a path`);
      opts[flags[argv[i]]] = path.resolve(argv[++i]);
    } else rest.push(argv[i]);
  }
  return { opts, rest };
}

async function main(argv) {
  const { opts, rest } = options(argv);
  const [command, file] = rest;
  if (command === "dump") {
    const { texts } = readWeb(opts);
    process.stdout.write(
      JSON.stringify(
        texts.map(({ key, text }) => ({ key, text })),
        null,
        1,
      ) + "\n",
    );
  } else if (command === "rows") {
    process.stdout.write(JSON.stringify(exportRows(opts), null, 1) + "\n");
  } else if (command === "apply" && file) {
    let rows;
    try {
      rows = JSON.parse(readFileSync(file, "utf8"));
    } catch (e) {
      throw new Refused(`Cannot read ${file}: ${e.message}`);
    }
    const web = readWeb(opts);
    const result = plan(rows, web, readServerText(opts.serverText));
    const outputs = await build(opts, web, result);
    writeAll(outputs);
    const changed = result.edits.map((e) => e.key);
    console.log(
      `Imported ${web.texts.length} web texts and ${result.server.length} server texts.` +
        (changed.length ? ` English changed: ${changed.join(", ")}.` : " No English was changed."),
    );
  } else {
    throw new Refused("Usage: node scripts/i18n/messages.mjs dump | rows | apply <rows.json>");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((e) => {
    console.error(e instanceof Refused ? e.message : e.stack);
    console.error("Nothing was written.");
    process.exit(1);
  });
}
